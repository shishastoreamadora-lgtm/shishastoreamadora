-- SHISHA STORE — Atualização 3: opiniões de clientes
-- Colar no Supabase → SQL Editor → New query → Run
-- (pode ser executado mais do que uma vez)
--  - Os clientes podem deixar uma opinião (estrelas + texto)
--  - Só aparece na loja depois de o dono a aprovar no painel
--  - Anti-spam: máx. 3 opiniões por dia do mesmo cliente e 30 por hora no total
-- =========================================================

create table if not exists public.reviews (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  produto     text check (produto is null or char_length(produto) <= 80),
  nome        text not null check (char_length(nome) between 2 and 40),
  estrelas    smallint not null check (estrelas between 1 and 5),
  texto       text not null check (char_length(texto) between 3 and 600),
  aprovado    boolean not null default false,
  resposta    text check (resposta is null or char_length(resposta) <= 400),
  ip_hash     text
);
create index if not exists reviews_created_idx on public.reviews (created_at desc);
create index if not exists reviews_ip_idx on public.reviews (ip_hash, created_at desc);

alter table public.reviews enable row level security;

-- Permissões: o público só vê as colunas visíveis (nunca o ip_hash)
revoke all on public.reviews from anon, authenticated;
grant select (id, created_at, produto, nome, estrelas, texto, resposta, aprovado) on public.reviews to anon;
grant insert (produto, nome, estrelas, texto) on public.reviews to anon;
grant select, insert, update, delete on public.reviews to authenticated;
grant usage, select on sequence public.reviews_id_seq to anon, authenticated;

drop policy if exists reviews_public_read on public.reviews;
create policy reviews_public_read on public.reviews for select to anon using (aprovado = true);

drop policy if exists reviews_public_insert on public.reviews;
create policy reviews_public_insert on public.reviews for insert to anon
  with check (aprovado = false and resposta is null);

drop policy if exists reviews_admin_all on public.reviews;
create policy reviews_admin_all on public.reviews for all to authenticated using (true) with check (true);

create or replace function public.reviews_before_insert()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare v_ip text; v_recent int;
begin
  new.nome  := btrim(regexp_replace(new.nome,  '[<>]', '', 'g'));
  new.texto := btrim(regexp_replace(new.texto, '[<>]', '', 'g'));

  -- O dono (com login) pode juntar opiniões já aprovadas
  if coalesce(auth.role(), 'anon') = 'authenticated' then
    return new;
  end if;

  begin
    v_ip := nullif(trim(split_part((current_setting('request.headers', true)::jsonb) ->> 'x-forwarded-for', ',', 1)), '');
  exception when others then v_ip := null;
  end;
  if v_ip is not null then
    new.ip_hash := md5(v_ip || 'shisha-store');
    select count(*) into v_recent from reviews
      where ip_hash = new.ip_hash and created_at > now() - interval '1 day';
    if v_recent >= 3 then
      raise exception 'Já deixaste várias opiniões hoje. Obrigado!';
    end if;
  end if;
  select count(*) into v_recent from reviews where created_at > now() - interval '1 hour';
  if v_recent >= 30 then
    raise exception 'Serviço ocupado. Tenta outra vez mais tarde.';
  end if;

  if new.produto is not null and not exists (select 1 from catalog where id = new.produto) then
    new.produto := null;
  end if;
  new.aprovado := false;
  new.resposta := null;
  new.created_at := now();
  return new;
end;
$$;

drop trigger if exists reviews_before_insert on public.reviews;
create trigger reviews_before_insert
  before insert on public.reviews
  for each row execute function public.reviews_before_insert();
